export const languageFor = (locale) => locale?.toLowerCase().startsWith("en") ? "en" : "tr";

export const translate = (locale, key, values = {}) => {
  const template = messages[languageFor(locale)][key] ?? messages.tr[key] ?? key;
  return template.replace(/{{(\w+)}}/g, (_, name) => String(values[name] ?? ""));
};